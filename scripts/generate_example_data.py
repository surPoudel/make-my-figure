def b_bar_error(rng):
    # qPCR-like relative signal across 4 treatment conditions, 6 replicates each.
    conditions = ["Control", "Drug_A", "Drug_B", "Combination"]
    means = {"Control": 1.0, "Drug_A": 1.6, "Drug_B": 0.7, "Combination": 2.1}
    rows = []
    for cond in conditions:
        for i in range(1, 7):
            rows.append({
                "condition": cond,
                "replicate": f"R{i}",
                "measurement": round(float(rng.normal(means[cond], 0.12)), 3),
                "unit": "relative_signal",
                "experiment_batch": f"Batch_{1 + (i - 1) % 2}",
            })
    return pd.DataFrame(rows), None


def b_grouped_bar(rng):
    # Gene expression by genotype x treatment (two-factor), 5 replicates.
    base = {("WT", "Vehicle"): 1.0, ("WT", "Stimulus"): 1.8,
            ("KO", "Vehicle"): 0.8, ("KO", "Stimulus"): 1.2}
    rows = []
    for geno in ["WT", "KO"]:
        for treat in ["Vehicle", "Stimulus"]:
            for i in range(1, 6):
                rows.append({
                    "genotype": geno, "treatment": treat, "replicate": f"R{i}",
                    "expression": round(float(rng.normal(base[(geno, treat)], 0.1)), 3),
                    "gene": "IL6", "unit": "relative_mRNA",
                })
    return pd.DataFrame(rows), None


def b_box_violin(rng):
    # Biomarker level across three clinical groups, ~24 samples each.
    groups = {"Healthy": 4.5, "Disease": 6.2, "Treated": 5.2}
    rows = []
    n = 0
    for grp, mu in groups.items():
        for _ in range(24):
            n += 1
            rows.append({
                "sample_id": f"S{n:03d}", "group": grp,
                "value": round(float(rng.normal(mu, 0.6)), 3),
                "batch": f"Batch_{rng.integers(1, 4)}",
                "sex": rng.choice(["M", "F"]),
            })
    return pd.DataFrame(rows), None


def b_scatter(rng):
    # Two response groups with different marker-vs-response slopes.
    rows = []
    n = 0
    for grp, slope, intercept, count in [("Responder", 1.4, 1.0, 35),
                                         ("Non_responder", 0.5, 3.0, 25)]:
        for _ in range(count):
            n += 1
            x = float(rng.uniform(1, 9))
            y = slope * x + intercept + float(rng.normal(0, 1.0))
            rows.append({"sample_id": f"S{n:03d}", "x_marker": round(x, 3),
                         "y_response": round(y, 3), "group": grp,
                         "label": f"S{n:03d}" if rng.random() < 0.08 else ""})
    return pd.DataFrame(rows), None


def b_line_timecourse(rng):
    # Signal over time for three treatments, 4 replicates each.
    times = [0, 2, 4, 8, 12, 24, 48]
    rows = []
    for treat in ["Vehicle", "Drug_A", "Drug_B"]:
        for rep in range(1, 5):
            for t in times:
                if treat == "Vehicle":
                    mu = 1.0 + 0.018 * t
                elif treat == "Drug_A":
                    mu = 1.0 + 1.2 * (1 - np.exp(-t / 10.0))
                else:  # Drug_B: rise then fall
                    mu = 1.0 + 1.1 * np.exp(-((t - 12) ** 2) / 120.0)
                rows.append({"time_hours": t, "treatment": treat, "replicate": f"R{rep}",
                             "signal": round(float(mu + rng.normal(0, 0.05)), 3),
                             "unit": "fold_change"})
    return pd.DataFrame(rows), None


def b_heatmap(rng):
    # 30 genes x 12 samples (Ctrl/DrugA/DrugB) z-scored, with block structure.
    samples = [f"{p}_{i}" for p in ["Ctrl", "DrugA", "DrugB"] for i in range(1, 5)]
    rows = []
    for g in range(1, 31):
        vals = rng.normal(0, 0.5, len(samples))
        if g <= 10:        # up in DrugA
            vals[4:8] += 1.5
        elif g <= 20:      # up in DrugB
            vals[8:12] += 1.5
        else:              # down in both drugs
            vals[4:12] -= 1.2
        row = {"gene": f"Gene_{g:02d}"}
        row.update({s: round(float(v), 3) for s, v in zip(samples, vals)})
        rows.append(row)
    return pd.DataFrame(rows), None


def b_volcano(rng):
    # 500 features differential expression results.
    n = 500
    lfc = rng.normal(0, 1.1, n)
    # spike in some strong up/down regulated genes
    lfc[:40] += rng.uniform(1.5, 4.0, 40)
    lfc[40:80] -= rng.uniform(1.5, 4.0, 40)
    # p-value smaller for larger |lfc|
    base = rng.uniform(0, 1, n)
    pval = np.clip(base * np.exp(-np.abs(lfc)), 1e-12, 1.0)
    adj = np.clip(pval * 5.0, 1e-12, 1.0)
    classes = rng.choice(["immune", "metabolic", "other"], n, p=[0.2, 0.2, 0.6])
    rows = []
    for i in range(n):
        sig = (abs(lfc[i]) >= 1.0) and (adj[i] <= 0.05)
        rows.append({"gene": f"GENE{i+1:04d}", "log2_fold_change": round(float(lfc[i]), 4),
                     "p_value": float(f"{pval[i]:.4e}"), "adjusted_p_value": float(f"{adj[i]:.4e}"),
                     "gene_class": classes[i],
                     "label": f"GENE{i+1:04d}" if sig and rng.random() < 0.3 else ""})
    return pd.DataFrame(rows), None


def b_enrichment(rng):
    terms = [
        ("Interferon gamma response", "Hallmark"), ("Oxidative phosphorylation", "Hallmark"),
        ("Epithelial migration", "GO_BP"), ("Cell cycle checkpoint", "Reactome"),
        ("Antigen processing", "GO_BP"), ("Complement cascade", "Reactome"),
        ("DNA repair", "Hallmark"), ("T cell activation", "GO_BP"),
        ("Apoptosis", "Hallmark"), ("mTOR signaling", "Reactome"),
        ("Extracellular matrix", "GO_CC"), ("Hypoxia", "Hallmark"),
    ]
    rows = []
    for term, cat in terms:
        ratio = float(rng.uniform(0.05, 0.35))
        count = int(rng.integers(20, 70))
        fdr = float(10 ** (-rng.uniform(1.5, 5.0)))
        rows.append({"term": term, "category": cat, "gene_ratio": round(ratio, 3),
                     "gene_count": count, "fdr": float(f"{fdr:.3e}"),
                     "neg_log10_fdr": round(float(-np.log10(fdr)), 3)})
    return pd.DataFrame(rows), None


def b_kaplan_meier(rng):
    # Survival times for low- vs high-risk groups (~30% censored).
    rows = []
    n = 0
    for grp, scale in [("Low_risk", 34.0), ("High_risk", 14.0)]:
        for _ in range(60):
            n += 1
            t = float(rng.exponential(scale))
            t = min(t, 60.0)
            censored = (t >= 60.0) or (rng.random() < 0.25)
            rows.append({"sample_id": f"{'Lo' if grp=='Low_risk' else 'Hi'}_{n:03d}",
                         "group": grp, "time_months": round(t, 2),
                         "event": 0 if censored else 1,
                         "censor_reason": "lost_to_followup" if censored else ""})
    return pd.DataFrame(rows), None


def b_stacked(rng):
    # Cell-type composition fractions per sample (sum to 1), two groups.
    cell_types = ["T_cell", "B_cell", "Myeloid", "Stromal", "Epithelial"]
    rows = []
    for i in range(1, 31):
        grp = "Control" if i <= 15 else "Treated"
        alpha = [3, 2, 2, 1.5, 1.5] if grp == "Control" else [2, 1.5, 3, 1.5, 2]
        fracs = rng.dirichlet(alpha)
        for ct, f in zip(cell_types, fracs):
            rows.append({"sample_id": f"S{i:02d}", "group": grp, "cell_type": ct,
                         "fraction": round(float(f), 4)})
    return pd.DataFrame(rows), None


def b_waterfall(rng):
    # Best % change in tumor size per patient (oncology waterfall).
    rows = []
    for i in range(1, 41):
        val = float(np.clip(rng.normal(-15, 35), -95, 60))
        cat = "PR" if val <= -30 else ("PD" if val >= 20 else "SD")
        rows.append({"patient_id": f"P{i:03d}", "treatment_arm": rng.choice(["Arm_A", "Arm_B"]),
                     "best_percent_change": round(val, 1), "response_category": cat,
                     "duration_months": round(float(rng.uniform(1, 18)), 1)})
    return pd.DataFrame(rows), None


def b_pca(rng):
    # Expression matrix (50 genes x 12 samples) + sample metadata.
    samples = [f"S{i:02d}" for i in range(1, 13)]
    groups = ["Control"] * 6 + ["Treated"] * 6
    batches = [f"Batch_{1 + (i % 2)}" for i in range(12)]
    mat = rng.normal(5.0, 0.8, (50, 12))
    # group separation on first 20 genes; mild batch effect
    for j in range(12):
        if groups[j] == "Treated":
            mat[:20, j] += 1.3
        if batches[j] == "Batch_2":
            mat[:, j] += 0.4
    matrix = pd.DataFrame(mat.round(3), columns=samples)
    matrix.insert(0, "gene", [f"Gene_{i:03d}" for i in range(1, 51)])
    meta = pd.DataFrame({
        "sample_id": samples, "group": groups, "batch": batches,
        "library_size_millions": [round(float(rng.uniform(20, 40)), 2) for _ in samples],
    })
    return matrix, meta


def b_oncoprint(rng):
    genes = ["TP53", "PIK3CA", "KRAS", "EGFR", "PTEN", "MYC", "BRAF", "APC", "ALK", "CDKN2A"]
    patients = [f"P{i:03d}" for i in range(1, 25)]
    alts = ["Missense", "Truncating", "Amplification", "Deletion", "Fusion"]
    rows = []
    for gi, gene in enumerate(genes):
        freq = 0.5 * (1 - gi / len(genes)) + 0.08   # higher genes mutated more often
        for pat in patients:
            if rng.random() < freq:
                a = rng.choice(alts, p=[0.45, 0.2, 0.15, 0.12, 0.08])
                rows.append({"patient_id": pat, "gene": gene, "alteration_type": a,
                             "variant_annotation": "p.X" if a in ("Missense", "Truncating") else a,
                             "variant_allele_fraction": round(float(rng.uniform(0.1, 0.9)), 2)
                             if a in ("Missense", "Truncating") else ""})
    return pd.DataFrame(rows), None


def b_lollipop(rng):
    types = ["Missense", "Nonsense", "Frameshift", "In_frame_del"]
    rows = []
    used = set()
    for _ in range(40):
        pos = int(rng.integers(20, 950))
        if pos in used:
            continue
        used.add(pos)
        mt = rng.choice(types, p=[0.6, 0.15, 0.15, 0.1])
        domain = "Kinase" if 300 <= pos <= 600 else ("SH2" if 700 <= pos <= 820 else "Other")
        rows.append({"gene": "GENE_X", "protein_position": pos,
                     "amino_acid_change": f"p.{rng.choice(list('ACDEFGHIKLMNPQRSTVWY'))}{pos}"
                                          f"{rng.choice(list('ACDEFGHIKLMNPQRSTVWY*'))}",
                     "mutation_type": mt, "sample_count": int(rng.integers(1, 12)),
                     "domain": domain})
    return pd.DataFrame(rows).sort_values("protein_position").reset_index(drop=True), None


def b_roc(rng):
    # Binary labels + scores from a strong model A and weaker model B.
    rows = []
    for i in range(1, 121):
        label = 0 if i <= 60 else 1
        cohort = "Discovery" if i % 2 == 0 else "Validation"
        a = float(np.clip(rng.normal(0.7 if label else 0.35, 0.13), 0, 1))
        b = float(np.clip(rng.normal(0.6 if label else 0.45, 0.18), 0, 1))
        rows.append({"sample_id": f"S{i:03d}", "true_label": label,
                     "score_model_a": round(a, 4), "score_model_b": round(b, 4),
                     "cohort": cohort})
    return pd.DataFrame(rows), None


def b_forest(rng):
    subgroups = ["All patients", "Age < 65", "Age >= 65", "Male", "Female",
                 "Biomarker high", "Biomarker low", "Prior therapy yes", "Prior therapy no"]
    rows = []
    for i, sg in enumerate(subgroups):
        hr = float(np.clip(rng.normal(1.0, 0.35), 0.3, 2.2))
        se = float(rng.uniform(0.12, 0.3))
        rows.append({"study": f"Study_{i+1}", "subgroup": sg,
                     "hazard_ratio": round(hr, 3),
                     "ci_low": round(hr * np.exp(-1.96 * se), 3),
                     "ci_high": round(hr * np.exp(1.96 * se), 3),
                     "p_value": round(float(rng.uniform(0.005, 0.4)), 4),
                     "n": int(rng.integers(80, 400))})
    return pd.DataFrame(rows), None


def b_ridge(rng):
    # Single-cell-like score distribution along pseudotime per condition.
    rows = []
    n = 0
    for cond, loc in [("Control", 0.35), ("Stimulated", 0.6), ("Inhibited", 0.25)]:
        for _ in range(350):
            n += 1
            pt = float(np.clip(rng.normal(loc, 0.18), 0, 1))
            rows.append({"cell_id": f"C{n:04d}",
                         "sample_id": f"{cond[:3]}_S{rng.integers(1,4)}",
                         "condition": cond, "pseudotime": round(pt, 4),
                         "score": round(float(rng.normal(3 + 2 * pt, 0.7)), 3)})
    return pd.DataFrame(rows), None


