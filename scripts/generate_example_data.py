def b_bar_error(rng):
    # qPCR-like relative signal across 4 treatment conditions, 6 replicates each.
    conditions = ["Control", "Drug_A", "Drug_B", "Combination"]
    means = {"Control": 1.0, "Drug_A": 1.6, "Drug_B": 0.7, "Combination": 2.1}
    rows = []
    for cond in conditions:
        for i in range(1, 7):
            rows.append({
                "condition": cond,
                "replicate": f"R{i}",
                "measurement": round(float(rng.normal(means[cond], 0.12)), 3),
                "unit": "relative_signal",
                "experiment_batch": f"Batch_{1 + (i - 1) % 2}",
            })
    return pd.DataFrame(rows), None


