def b_line_timecourse(rng):
    # Signal over time for three treatments, 4 replicates each.
    times = [0, 2, 4, 8, 12, 24, 48]
    rows = []
    for treat in ["Vehicle", "Drug_A", "Drug_B"]:
        for rep in range(1, 5):
            for t in times:
                if treat == "Vehicle":
                    mu = 1.0 + 0.018 * t
                elif treat == "Drug_A":
                    mu = 1.0 + 1.2 * (1 - np.exp(-t / 10.0))
                else:  # Drug_B: rise then fall
                    mu = 1.0 + 1.1 * np.exp(-((t - 12) ** 2) / 120.0)
                rows.append({"time_hours": t, "treatment": treat, "replicate": f"R{rep}",
                             "signal": round(float(mu + rng.normal(0, 0.05)), 3),
                             "unit": "fold_change"})
    return pd.DataFrame(rows), None


def b_heatmap(rng):
    # 30 genes x 12 samples (Ctrl/DrugA/DrugB) z-scored, with block structure.
    samples = [f"{p}_{i}" for p in ["Ctrl", "DrugA", "DrugB"] for i in range(1, 5)]
    rows = []
    for g in range(1, 31):
        vals = rng.normal(0, 0.5, len(samples))
        if g <= 10:        # up in DrugA
            vals[4:8] += 1.5
        elif g <= 20:      # up in DrugB
            vals[8:12] += 1.5
        else:              # down in both drugs
            vals[4:12] -= 1.2
        row = {"gene": f"Gene_{g:02d}"}
        row.update({s: round(float(v), 3) for s, v in zip(samples, vals)})
        rows.append(row)
    return pd.DataFrame(rows), None


def b_volcano(rng):
    # 500 features differential expression results.
    n = 500
    lfc = rng.normal(0, 1.1, n)
    # spike in some strong up/down regulated genes
    lfc[:40] += rng.uniform(1.5, 4.0, 40)
    lfc[40:80] -= rng.uniform(1.5, 4.0, 40)
    # p-value smaller for larger |lfc|
    base = rng.uniform(0, 1, n)
    pval = np.clip(base * np.exp(-np.abs(lfc)), 1e-12, 1.0)
    adj = np.clip(pval * 5.0, 1e-12, 1.0)
    classes = rng.choice(["immune", "metabolic", "other"], n, p=[0.2, 0.2, 0.6])
    rows = []
    for i in range(n):
        sig = (abs(lfc[i]) >= 1.0) and (adj[i] <= 0.05)
        rows.append({"gene": f"GENE{i+1:04d}", "log2_fold_change": round(float(lfc[i]), 4),
                     "p_value": float(f"{pval[i]:.4e}"), "adjusted_p_value": float(f"{adj[i]:.4e}"),
                     "gene_class": classes[i],
                     "label": f"GENE{i+1:04d}" if sig and rng.random() < 0.3 else ""})
    return pd.DataFrame(rows), None


