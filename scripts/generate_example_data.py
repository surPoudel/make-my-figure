"""Reproducible generator for Make My Figure example/template datasets.

Creates, for every plot type the app supports, a clean *synthetic* dataset plus
a CSV/TSV/XLSX copy, a PlotSpec JSON, and a README — under
``examples/by_plot_type/<slug>/`` — a combined workbook, and a machine-readable
manifest.

IMPORTANT: All bundled example data are SYNTHETIC (generated here with a fixed
seed). They look scientifically plausible but are NOT real measurements and must
not be cited as biological findings. Published papers/figures are used by this
project only as visual style references (layout, typography, panels, legends) —
never as a source of copied data.

Safe to re-run: it only writes inside ``examples/``.

Usage:
    python scripts/generate_example_data.py
"""

