"""Generate the deterministic SIMULATED tutorial datasets.

Every table here is synthetic. Values are drawn from fixed-seed random number generators and
carry no biological meaning. They exist so that a small set of files can support many plot
types and so that screenshots and videos are reproducible.

Usage:  python tutorial/datasets/make_tutorial_datasets.py
Writes CSV files next to this script and tutorial/datasets/README.md (regenerated).
"""
from __future__ import annotations

import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = 20260922
NOTE = "SIMULATED TUTORIAL DATA - generated by make_tutorial_datasets.py, no biological meaning."


def _rng(offset: int) -> np.random.Generator:
    return np.random.default_rng(SEED + offset)


def general_long_table() -> pd.DataFrame:
    """One measurement per sample; three conditions x six replicates x two batches."""
    rng = _rng(1)
    rows = []
    means = {"Control": 10.0, "Treatment A": 13.5, "Treatment B": 12.0}
    i = 0
    for cond, mu in means.items():
        for batch in ("B1", "B2"):
            for rep in range(1, 7):
                i += 1
                rows.append({"sample_id": f"S{i:02d}", "condition": cond, "batch": batch,
                             "replicate": rep,
                             "measurement": round(float(rng.normal(mu + (0.6 if batch == "B2" else 0.0), 1.4)), 3),
                             "unit": "AU"})
    return pd.DataFrame(rows)


def group_comparison() -> pd.DataFrame:
    """Three groups with unequal sizes (8, 10, 12) for box / violin / bar / strip plots."""
    rng = _rng(2)
    rows = []
    spec = [("Vehicle", 8, 4.0, 1.0), ("Low dose", 10, 4.6, 1.1), ("High dose", 12, 6.3, 1.3)]
    k = 0
    for group, n, mu, sd in spec:
        for _ in range(n):
            k += 1
            rows.append({"subject_id": f"P{k:03d}", "group": group,
                         "sex": rng.choice(["F", "M"]),
                         "response": round(float(rng.normal(mu, sd)), 2),
                         "baseline": round(float(rng.normal(3.9, 0.8)), 2)})
    return pd.DataFrame(rows)


def relationship_data() -> pd.DataFrame:
    """Two correlated readouts plus a dose column and a categorical colour role."""
    rng = _rng(3)
    n = 60
    dose = np.round(np.repeat(np.array([0.0, 0.1, 0.3, 1.0, 3.0, 10.0]), n // 6), 2)
    line = rng.choice(["Line 1", "Line 2"], size=n)
    expr_a = np.round(rng.normal(8.0, 1.2, n), 3)
    expr_b = np.round(0.7 * expr_a + rng.normal(2.0, 0.6, n), 3)
    viability = np.round(100 / (1 + (dose / 1.2) ** 1.1) + rng.normal(0, 4, n), 1)
    return pd.DataFrame({"sample": [f"R{i:02d}" for i in range(1, n + 1)], "cell_line": line,
                         "dose_um": dose, "viability_pct": viability,
                         "expression_a": expr_a, "expression_b": expr_b})


def time_course() -> pd.DataFrame:
    """Long table: signal measured at six times for two conditions, five subjects each."""
    rng = _rng(4)
    rows = []
    for cond, slope in (("Control", 0.15), ("Stimulated", 0.55)):
        for subj in range(1, 6):
            base = rng.normal(1.0, 0.15)
            for t in (0, 2, 4, 8, 12, 24):
                rows.append({"subject": f"{cond[:4].upper()}_{subj}", "condition": cond, "time_h": t,
                             "signal": round(float(base + slope * np.log1p(t) + rng.normal(0, 0.08)), 3)})
    return pd.DataFrame(rows)


def rnaseq_results() -> pd.DataFrame:
    """Simulated differential-expression result table (DESeq2-like column names)."""
    rng = _rng(5)
    n = 1200
    gene_id = [f"GENE{i:05d}" for i in range(1, n + 1)]
    symbol = [f"G{i}" for i in range(1, n + 1)]
    base_mean = np.round(np.exp(rng.normal(5.0, 1.5, n)), 2)
    lfc = rng.normal(0.0, 0.6, n)
    hot = rng.choice(n, size=90, replace=False)
    lfc[hot] += rng.choice([-1, 1], size=90) * rng.uniform(1.5, 4.5, size=90)
    lfc = np.round(lfc, 4)
    se = np.round(rng.uniform(0.15, 0.5, n), 4)
    z = lfc / se
    from scipy.stats import norm
    p = 2 * norm.sf(np.abs(z))
    p = np.clip(p, 1e-300, 1.0)
    order = np.argsort(p)
    padj = np.empty(n)
    ranked = p[order] * n / (np.arange(n) + 1)
    padj[order] = np.minimum.accumulate(ranked[::-1])[::-1]
    padj = np.clip(padj, 0, 1)
    sig = np.where((padj < 0.05) & (lfc > 1), "Up", np.where((padj < 0.05) & (lfc < -1), "Down", "NS"))
    annotation = rng.choice(["protein_coding", "lncRNA", "pseudogene"], size=n, p=[0.8, 0.15, 0.05])
    return pd.DataFrame({"gene_id": gene_id, "gene_symbol": symbol, "baseMean": base_mean,
                         "log2FoldChange": lfc, "lfcSE": se, "pvalue": p, "padj": padj,
                         "significance": sig, "annotation": annotation})


def rnaseq_results_renamed(de: pd.DataFrame) -> pd.DataFrame:
    """The same table with non-standard column names - for the manual-mapping tutorial."""
    return de.rename(columns={"gene_id": "feature", "gene_symbol": "name", "baseMean": "mean_expr",
                              "log2FoldChange": "effect_measure", "pvalue": "p_raw",
                              "padj": "p_adjusted", "significance": "call"})


def feature_sample_matrix() -> pd.DataFrame:
    """Feature x sample matrix: 200 features, 12 samples (two groups of six), log2 scale."""
    rng = _rng(6)
    n_feat, samples = 200, [f"S{i:02d}" for i in range(1, 13)]
    base = rng.normal(8.0, 1.5, (n_feat, 1))
    mat = base + rng.normal(0, 0.35, (n_feat, 12))
    de_idx = rng.choice(n_feat, 30, replace=False)
    mat[de_idx, 6:] += rng.choice([-1, 1], size=(30, 1)) * rng.uniform(1.0, 2.5, size=(30, 1))
    df = pd.DataFrame(np.round(mat, 3), columns=samples)
    df.insert(0, "gene_symbol", [f"G{i}" for i in range(1, n_feat + 1)])
    df.insert(0, "gene_id", [f"GENE{i:05d}" for i in range(1, n_feat + 1)])
    return df


def sample_metadata() -> pd.DataFrame:
    rng = _rng(7)
    samples = [f"S{i:02d}" for i in range(1, 13)]
    return pd.DataFrame({"sample_id": samples,
                         "group": ["Control"] * 6 + ["Treated"] * 6,
                         "batch": ["B1", "B2"] * 6,
                         "sex": rng.choice(["F", "M"], size=12)})


def survival() -> pd.DataFrame:
    rng = _rng(8)
    rows = []
    for arm, scale in (("Standard", 18.0), ("Experimental", 30.0)):
        for i in range(40):
            t = rng.exponential(scale)
            censor = rng.uniform(6, 48)
            event = int(t <= censor)
            rows.append({"patient_id": f"{arm[:3].upper()}{i + 1:03d}", "arm": arm,
                         "time_months": round(float(min(t, censor)), 1), "event": event,
                         "age_group": rng.choice(["<50", "50+"])})
    return pd.DataFrame(rows)


def mutation_matrix() -> pd.DataFrame:
    """Long table for the oncoprint: one row per (sample, gene) alteration."""
    rng = _rng(9)
    genes = ["TP53", "KRAS", "PIK3CA", "EGFR", "BRAF", "PTEN", "APC", "MYC"]
    freq = [0.55, 0.35, 0.25, 0.2, 0.15, 0.15, 0.1, 0.1]
    kinds = ["Missense", "Truncating", "Amplification", "Deletion"]
    rows = []
    for s in range(1, 31):
        for g, f in zip(genes, freq):
            if rng.uniform() < f:
                rows.append({"sample": f"T{s:02d}", "gene": g,
                             "alteration": rng.choice(kinds, p=[0.5, 0.25, 0.15, 0.1])})
    return pd.DataFrame(rows)


def network() -> pd.DataFrame:
    rng = _rng(10)
    nodes = [f"N{i}" for i in range(1, 16)]
    rows, seen = [], set()
    while len(rows) < 32:
        a, b = rng.choice(nodes, 2, replace=False)
        key = tuple(sorted((a, b)))
        if key in seen:
            continue
        seen.add(key)
        rows.append({"source": a, "target": b, "weight": round(float(rng.uniform(0.2, 1.0)), 2),
                     "interaction_type": rng.choice(["activation", "inhibition", "binding"])})
    return pd.DataFrame(rows)


def effect_estimates() -> pd.DataFrame:
    rng = _rng(11)
    rows = []
    for i in range(1, 9):
        est = rng.normal(0.85, 0.2)
        half = rng.uniform(0.1, 0.35)
        rows.append({"study": f"Study {i}", "estimate": round(est, 3),
                     "ci_lower": round(est - half, 3), "ci_upper": round(est + half, 3),
                     "n": int(rng.integers(40, 400))})
    return pd.DataFrame(rows)


def paired_data() -> pd.DataFrame:
    rng = _rng(12)
    rows = []
    for i in range(1, 13):
        before = rng.normal(50, 8)
        after = before + rng.normal(6, 5)
        rows.append({"subject": f"Sub{i:02d}", "condition": "Before", "value": round(before, 1)})
        rows.append({"subject": f"Sub{i:02d}", "condition": "After", "value": round(after, 1)})
    return pd.DataFrame(rows)


def categorical_data() -> pd.DataFrame:
    """Composition per sample (fractions sum to 1) with a grouping column."""
    rng = _rng(13)
    rows = []
    for s in range(1, 13):
        group = "Control" if s <= 6 else "Treated"
        alpha = np.array([4, 3, 2, 1]) + (np.array([0, 2, 0, 0]) if group == "Treated" else 0)
        frac = rng.dirichlet(alpha)
        for cat, f in zip(["T cell", "B cell", "Myeloid", "Other"], frac):
            rows.append({"sample_id": f"S{s:02d}", "group": group, "cell_type": cat,
                         "fraction": round(float(f), 4)})
    return pd.DataFrame(rows)


def ambiguous_columns() -> pd.DataFrame:
    """Deliberately non-standard column names. Same shape as a group comparison table.

    col_A          -> sample identifier text
    measurement_2  -> the numeric readout (Y)
    condition_code -> the group (coded C0 / C1 / C2)
    thing          -> a free-text label per row
    score_final    -> a second numeric readout
    id_value       -> an integer identifier
    """
    rng = _rng(14)
    rows = []
    means = {"C0": 2.0, "C1": 2.9, "C2": 3.8}
    k = 0
    for code, mu in means.items():
        for _ in range(9):
            k += 1
            rows.append({"col_A": f"item_{k:02d}", "measurement_2": round(float(rng.normal(mu, 0.5)), 3),
                         "condition_code": code, "thing": f"label{k}",
                         "score_final": round(float(rng.normal(10 + 2 * mu, 1.5)), 2),
                         "id_value": 1000 + k})
    return pd.DataFrame(rows)


def one_table_many_plots() -> pd.DataFrame:
    """One table that supports scatter, regression, box, violin, strip, bar, histogram, ridge.

    treatment (3 groups) x dose_um (numeric) with response and viability readouts.
    """
    rng = _rng(15)
    rows = []
    k = 0
    for trt, shift in (("Vehicle", 0.0), ("Compound X", 1.8), ("Compound Y", 3.2)):
        for dose in (0.1, 0.3, 1.0, 3.0, 10.0):
            for rep in range(1, 5):
                k += 1
                resp = 5 + shift + 1.6 * np.log10(dose) * (1 if trt != "Vehicle" else 0.2) + rng.normal(0, 0.7)
                viab = 95 - 6 * np.log10(dose) * (1 if trt != "Vehicle" else 0.1) - 0.8 * shift + rng.normal(0, 3)
                rows.append({"sample_id": f"W{k:03d}", "treatment": trt, "dose_um": dose,
                             "replicate": rep, "response": round(float(resp), 3),
                             "viability_pct": round(float(min(viab, 100.0)), 1),
                             "batch": "B1" if rep <= 2 else "B2"})
    return pd.DataFrame(rows)


def main() -> int:
    de = rnaseq_results()
    tables = {
        "general_long_table.csv": general_long_table(),
        "group_comparison.csv": group_comparison(),
        "relationship_data.csv": relationship_data(),
        "time_course.csv": time_course(),
        "rnaseq_results.csv": de,
        "rnaseq_results_renamed.csv": rnaseq_results_renamed(de),
        "feature_sample_matrix.csv": feature_sample_matrix(),
        "sample_metadata.csv": sample_metadata(),
        "survival.csv": survival(),
        "mutation_matrix.csv": mutation_matrix(),
        "network.csv": network(),
        "effect_estimates.csv": effect_estimates(),
        "paired_data.csv": paired_data(),
        "categorical_data.csv": categorical_data(),
        "ambiguous_columns.csv": ambiguous_columns(),
        "one_table_many_plots.csv": one_table_many_plots(),
    }
    manifest = {"note": NOTE, "seed": SEED, "files": {}}
    for name, df in tables.items():
        path = os.path.join(HERE, name)
        df.to_csv(path, index=False)
        manifest["files"][name] = {"rows": int(df.shape[0]), "columns": list(df.columns)}
        print(f"{name:32s} {df.shape[0]:5d} x {df.shape[1]}")
    with open(os.path.join(HERE, "datasets_manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
