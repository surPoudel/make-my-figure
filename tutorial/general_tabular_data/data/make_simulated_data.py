"""Write ``simulated_bee_factorial.csv`` - a SIMULATED, replicated factorial dataset.

The numbers are generated by this script (fixed seed). They are shaped like an
insect-behaviour experiment so the tutorial reads naturally, but they are NOT
observations of real bees, are not from any publication, and must not be
reported as biological results.

Design: treatment (control, exposed) x social setting (isolated, paired, group)
x time (day 2, day 4); 4 colonies per combination, one bee per colony (48 rows,
every row an independent experimental unit). Built in:
* a treatment effect and a treatment x time interaction on the log scale;
* body size as a covariate with a small positive slope;
* a response spanning roughly 10^4 - 10^7, so a log axis is worth using.

Run:  python tutorial/general_tabular_data/data/make_simulated_data.py
"""
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))


def build() -> pd.DataFrame:
    rng = np.random.default_rng(20261013)
    rows, k = [], 0
    for trt in ("control", "exposed"):
        for soc in ("isolated", "paired", "group"):
            for day in (2, 4):
                for _ in range(4):
                    k += 1
                    size = round(float(rng.normal(3.4, 0.25)), 2)
                    log10_mu = (5.3 + 0.6 * (trt == "exposed") + 0.15 * (day == 4)
                                + 0.5 * (trt == "exposed") * (day == 4) + 0.3 * (size - 3.4))
                    q = 10 ** (log10_mu + rng.normal(0, 0.35))
                    rows.append({"colony id": f"C{k:02d}", "treatment": trt, "social setting": soc,
                                 "time (day)": day, "bee body size_mm": size,
                                 "quantity per bee": int(round(q))})
    return pd.DataFrame(rows)


if __name__ == "__main__":
    build().to_csv(os.path.join(HERE, "simulated_bee_factorial.csv"), index=False, lineterminator="\n")
